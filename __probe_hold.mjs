import { chromium } from "@playwright/test";
import { writeFileSync } from "node:fs";
const out = process.argv[2]; const target = process.argv[3] || "/"; const holdMs = Number(process.argv[4] || 40000);
const browser = await chromium.launch();
const page = await (await browser.newContext()).newPage();
const t0 = Date.now(); const ev = [];
const log = (s) => ev.push(`+${String(Date.now()-t0).padStart(6)} ${s}`);
page.on("framenavigated", (f) => { if (f === page.mainFrame()) log(`NAV ${f.url()}`); });
page.on("request", (r) => { if (r.resourceType() === "document") log(`REQ document ${r.url().replace("http://localhost:3141","")}`); });
page.on("websocket", (ws) => { log(`WS open ${ws.url().slice(0,70)}`); ws.on("framesent", (f) => { const p = String(f.payload); if (!p.includes('"browser-logs"') && !p.includes('"client-success"')) log(`WS>> ${p.slice(0,200)}`); }); ws.on("framereceived", (f) => { const p = String(f.payload); if (p.startsWith("{")) log(`WS<< ${p.slice(0,220)}`); }); ws.on("close", () => log(`WS close`)); });
page.on("console", (m) => { const t = m.text(); if (/HMR|Fast Refresh|reload/i.test(t)) log(`CON ${t.slice(0,120).replace(/\n/g," ")}`); });
await page.goto(`http://localhost:3141${target}`, { waitUntil: "load" }).catch((e) => log(`goto failed: ${e.message.slice(0,100)}`));
await page.waitForTimeout(holdMs);
writeFileSync(out, ev.join("\n") + "\n");
await browser.close();
