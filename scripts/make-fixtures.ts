// D24: deterministic fixtures/<model>/<scenario>.jsonl from the scenario scripts, so replay mode
// needs no recordings or API key. RECORD=1 recordings in fixtures/recorded/ can replace them.
import fs from "node:fs";
import path from "node:path";
import { MODEL_IDS } from "../src/shared/models";
import { scriptToFixture } from "../src/relay/providers/scripted";
import { SCENARIO_NAMES, scenarioScript } from "../src/relay/scenarios";

const root = path.resolve(process.cwd(), "fixtures");
let files = 0;
for (const model of MODEL_IDS) {
  const dir = path.join(root, model);
  fs.mkdirSync(dir, { recursive: true });
  for (const scenario of SCENARIO_NAMES) {
    const script = scenarioScript(scenario, { model, thinking: { harder: false }, messages: [], scenario });
    const seed = [...`${model}/${scenario}`].reduce((h, c) => (h * 31 + c.charCodeAt(0)) >>> 0, 7);
    const lines = scriptToFixture(script, seed);
    const body = [`# generated by scripts/make-fixtures.ts: ${model} ${scenario}`, ...lines.map((l) => JSON.stringify(l))].join("\n");
    fs.writeFileSync(path.join(dir, `${scenario}.jsonl`), `${body}\n`);
    files++;
  }
}
console.log(`wrote ${files} fixture files under ${root}`);
